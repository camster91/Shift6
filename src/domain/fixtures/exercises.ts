function seed({
  id,
  name,
  movementPattern,
  classification,
  primaryMuscles,
  equipmentIds,
  difficulty = 'beginner',
  unilateral = false,
  trackingType = 'reps',
  tags = [],
}: ExerciseSeed): Exercise {
  return {
    id,
    name,
    aliases: [],
    movementPattern,
    classification: classification ?? inferClassification(primaryMuscles),
    primaryMuscles,
    secondaryMuscles: [],
    equipmentIds,
    setup: 'Use a stable setup and choose a load or variation you can control.',
    difficulty,
    instructions: [
      'Set up with the equipment and position described by the exercise name.',
      'Move through a controlled, comfortable range of motion.',
      'Return to the starting position without rushing the next repetition.',
    ],
    techniqueCues: [
      'Breathe steadily.',
      'Keep the movement controlled.',
      'Stop if sharp pain occurs.',
    ],
    commonMistakes: ['Rushing repetitions.', 'Using more load than can be controlled.'],
    safetyNotes: [
      'This draft record is not a diagnosis or individualized medical advice. Stop for sharp pain or concerning symptoms and seek appropriate guidance.',
    ],
    unilateral,
    trackingType,
    tags: [...new Set([movementPattern, ...tags])],
    media: [],
    isCustom: false,
    contentStatus: 'draft',
  };
}

function inferClassification(primaryMuscles: readonly string[]): ExerciseClassification {
  return primaryMuscles.length > 1 ? 'compound' : 'isolation';
}
